# 1 - Зависимость фреймворка
#  Синхронизация состояния виртуальных машин могла задерживать
#  общий поток периодических задач из-за ожидания блокировки одной ВМ. Механизм
# запуска задач был универсальным, но скорость выполнения остальных задач зависела
# от поведения конкретного обработчика, поэтому зависимости проверки вынесли в фоновый пул.
# Это явное и задукоментированное изменение, которое было сделано после набитых шишек.
# Хотя в общем-то скорее интуитивное, чем нет.

# 2 - зависимость от формата данных
# Здесь была история со взаимодействиями двух сервисов и nullable (антипаттерн немножко как будто)
# полями/пустыми словарями. На мой взгляд, данная проблема хорошо разрешается
# установлением и формализацией контракта и зависимостью от него. Но в практике работы
# считалось, что "неглавный" сервис зависит от "главного", подстраиваясь под его формат,
# что конечно как минимум неоднозначно.
# И здесь, на мой взгляд, интуиция скорее вредит.
# А помогает здесь четкий контракт, максимально простой и универсальный, при этом достаточно точный.
# Но чтобы написать такой контракт, нужно формализовать (или хотя бы с прицелом на точность описать)
# ограничения участвующих в нем систем. И как будто это может иногда приводить к совершенно
# контринтуитивным решениям.

# 3 - зависимость от зависимости
# Неоднократно были ситуации с рассинхроном таймаутов между компонентами пайплайнов, например.
# Вроде бы интуитивно должно пониматься, но это такая конкретика, которую легко забыть.
# На выходе получаем кучу ошибок на пустом месте.

# 4 - всё зависит от всего.
# Здесь как будто должно работать стратегическое мышление, однако есть нюанс.
# Оно не должно быть интуитивным, потому что обязано быть достаточно точным.
# А не-интуитивное стратегическое мышление - это крайне сложно.
# Но можно реструктурировать связи так, чтобы повысить вероятность успешного исхода,
# собственно, "глубокие" интерфейсы, low coupling и т.д.

# 5 - зависимость перебрасывания.
# Пример аналогичный, но, допустим, с картинками - возьмем сервисы генерации изображений В и С, от которых зависит А.
# С дороже и дольше, но стабильнее, с В все наоборот - дешевый и нестабильный. Зависит ли А от В?
# Здесь как будто вопрос надо из качественного перевести в количественный, т.е, "насколько зависит" вместо
# "зависит ли". А потом разбить на некоторое множество вопросов, которые интересуют нас в конкретный момент.
# Допустим, если задать вопрос абстрактно "можем ли мы обойтись без В"? Да, можем.
# "Можем ли мы обойтись без В в конкретной ситуации"? - неизвестно. "Во сколько ресурсов нам обойдется
# полный отказ от В?". "Как изменится работа системы при отказе от В?" "Можем ли мы себе позволить полный отказ от В?"
# "Хотим ли мы тратить х ресурсов и менять показатели системы на у ради увеличения стабильности на z?".
# И так далее. Здесь, на мой взгляд, ответ не интуитивен, потому что требует как минимум арифметических вычислений.
# Конечно, в ряде случаев на многие из этих вопросов можно ответить интуитивно (например, при малых нагрузках).
# Но далеко не всегда.
#
# Случай почти реальный - переезжали на другую библиотеку генерации картинок. Правда, на основе PDF.

# 6 - Ну, здесь как будто (интуитивно) есть намек на разделение интерфейсов и имплементации, а также зависимости
# как повода для изменения и зависимости как потребности в чем-то, что интерфейс корректно имплементирует.
# То есть, соответствует по поведению пред-постусловиям абстрактных методов.
# Или показалось...

# 7 - Интуитивно кажется, что здесь снова поможет количественно-качественный переход.
# Например, с сервисами оплаты и их пользователями - сервис-пользователь, который что-то оплачивает,
# в некотором смысле зависит от собственной способности подтвердить, что некое оплачиваемое им изменение
# успешно произошло. Разумеется, разные части сервиса-пользователя отвечают за разные вещи, но его можно
# представить и как единое целое.

# 8 - Зависимость высшего порядка.
# Здесь снова как будто разница в а) зависимостях на уровне вариантов работы логики и их изменения и
# б) на уровне условного рантайма. Также передача логики приложения (например, объекта с магическими методами),
# на мой взгляд (интуитивно) зависимостью варианта а) не является, поскольку, опять-таки, библиотека
# делает предположение о поведении и опирается на него. В конкретном случае с хэшами, опора на
# правило a == b -> hash(a) == hash(b). Это в некотором смысле инвертированная зависимость,
# зависимость от поведения, а не от объекта (ко-алгебра, если правильно понимаю).

# 9 - вероятно, здесь тоже зависимость в разном понимании. Судя по всему, в понимании
# опоры на х как на источник конечного решения и опоры на х как на источник информации для решения.
# Вероятно, это справедливо для любых систем с консенсусом. С ними, правда, пока прицельно не работал :)


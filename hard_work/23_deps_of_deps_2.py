# Б. Замена тома через RPC между сервисами.
#
# Зависимость: RPC-клиент ComputeAPI -> RPC-обработчик ComputeManager, метод swap_volume.
# Для выполнения команды обработчик должен знать имя команды и аргументы.
# Причем, в зависимости от версии имя и аргументы могут быть разные.
#
# Например, в RPC версии 4.20 сообщение содержит параметры sync_writes и
# copy_bandwidth_bytes_sec. Перед отправкой клиент проверяет версию
# принимающего хоста. Для старого хоста он удаляет эти два параметра
# и отправляет сообщение с версией 4.0.
# :)

# 1. Семантика
# Зависимость сборки - на этом уровне не проявится, т.к компоненты собираются независимо друг от друга
# Зависимость времени выполнения - а вот здесь уже могут начаться проблемы, поскольку неправильно
# сконфигурированные (с разными версиями) компоненты ожидают друг от друга разного поведения.
# В конкретном случае, API слой ожидает, что RPC обработчик как минимум находится в том диапазоне версий,
# которые допустимы (для API слоя).
# Функциональные требования
# - переключение тома через команду swap_volume
# предусловия: оба тома доступны узлу, принимающему команду, размер нового тома равен или больше размера старого,
# ВМ на принимающем команду узле, доступна для управления гипервизором (можно описать через набор обязательных
# критериев), нет конфликтующих параллельных операций
# постусловия:
# - успешное завершение -
# ВМ продолжает работать, данные перенесены на новый том, чтение и запись идут на новый том, старый том больше
# не используется этой ВМ
# - неуспешное завершение -
# выброшена ошибка, если переключение не произошло - проведены фолбек и очистка,
# если произошло - ВМ корректно приведена в целевое стабильное состояние

# 2. Характеристики - в данном случае от понимания формата
# сообщения и корректной обработки команды swap_volume зависит свойство вызывающей системы
# "иметь возможность заменить том у работающей ВМ с сохранением данных".
# Нефункциональные требования: допустимое время от отправки
# команды до завершения замены, нагрузка копирования на сеть/хранилище.

# 3. Допустимые изменения.
# Опираемся на пред- и постусловия операции, функциональные/нефункциональные требования
# и совместимость поддерживаемых версий клиента и обработчика.
# Суперспецификация:
# Допустимы любые изменения в реализации обработчика, которые:
# сохраняют возможность принять и выполнить команду от поддерживаемых версий клиента,
# сохраняют обработку ранее допустимых сообщений и смысл переданных в них аргументов,
# не усиливают предусловия операции,
# не ослабляют постусловия, в том числе требования к завершению операции с ошибкой,
# позволяют вызывающей системе сохранять свойство "иметь возможность заменить том
# у работающей ВМ с сохранением данных",
# обеспечивают работу в рамках выбранных ограничений на время от отправки команды
# до завершения замены и на нагрузку копирования на сеть/хранилище.


# В. Обращения к сервису образов с несколькими адресами серверов.
#
# Зависимость: код Nova, запрашивающий данные об образах -> сервис Glance (за образ отвечает).
# Для успешного запроса нужен ответ Glance. Серверов несколько, клиенты создаются специфично под сервер.
# За выбор адреса сервера и политику ретраев отвечает Wrapper (так уж сложилось).
#
# Wrapper вызывает методы клиента адрес очередного клиента выбирается
# из списка glance.api_servers, если эндпоинт не закреплен за сервером. При ряде ошибок
# обёртка повторяет запрос, число повторов ограничено настройкой glance.num_retries.

# Здесь случай чуть посложнее и поинтереснее

# 1. Семантика
# Зависимость сборки - Нова зависит от клиента, но не зависит от враппера. Враппер зависит от клиента.
# То есть сервис без враппера запустится. В данном случае транзитивная зависимость есть
# (от клиента), но она поглощается прямой зависимостью (от того же клиента), поэтому можно ее опустить.
# Клиент также не зависит от сервера на данном уровне (до первого запроса).
#
# Зависимость времени выполнения - здесь все строже - несмотря на то, что без враппера
# сервис запустился в прошлом пункте, и код клиента будет формально доступен для исполнения,
# без работающего враппера предоставляемый этим кодом функционал окажется недоступен, и поведение системы
# перестанет соответствовать заявляемому.
# Клиент же начинает жестко зависеть от сервера, выполняющего определенные действия в ответ на запросы.
# То есть, на данном этапе Нова уже транзитивно зависит от сервера образов.
#
# Функциональные требования
# - получение сведений об образе по его идентификатору через Wrapper.call.
# При ошибках ServiceUnavailable, InvalidEndpoint или CommunicationError во время выполнения запроса
# враппер повторяет обращение в пределах заданного числа попыток. Если endpoint не закреплён,
# для очередной попытки выбирается следующий адрес из списка, если закреплён - используется тот же клиент.
# предусловия:
# установлен совместимый клиент Glance и доступен код враппера
# переданы контекст доступа, поддерживаемая версия API, имя метода чтения и корректные аргументы,
# включая идентификатор образа
# задан явный endpoint либо непустой список адресов серверов сервиса образов,
# glance.num_retries - неотрицательное целое число,
# отказы отдельных серверов входят в предусмотренный сценарий работы.
# постусловия:
# - успешное завершение -
# возвращены сведения о запрошенном образе в формате, предусмотренном выбранным методом,
# после получения результата повторные попытки прекращены, запрос не изменил содержимое образа.
# - неуспешное завершение -
# если все разрешённые попытки закончились одной из перечисленных ошибок обращения, выброшено исключение
# ошибки, не входящие в список для повторов (например, отказ в доступе или отсутствие образа),
# переданы вызывающему коду без повторения запроса

# в обоих случаях число вызовов метода клиента со стороны враппера не превышает 1 + количество ретраев из конфига.

# 2. Характеристики
# От свойства клиента "иметь возможность предоставлять информацию об образах"
# зависит (транзитивно через несколько логических шагов) от свойства сервера "иметь возможность
# предоставлять информацию об образах", следовательно, свойство системы "иметь возможность получать сведения
# об образах" зависит от свойства "иметь возможность предоставлять информацию об образах" И клиента, И сервера.
# От враппера зависит свойство системы "иметь возможность получать сведения об образах
# с ретраями и выбором конкретного сервера образов".
#
# Формально враппер не является жёсткой сборочной зависимостью, его отсутствие не обязательно
# мешает запуску сервиса. Но описываемое свойство системы определяется её поведением в рантайме,
# а не наличием инициализированного клиента. А в текущем виде иначе чем через враппер управляющий слой
# к клиенту не обращается (в стандартных ситуациях).
#
# Поэтому в текущей реализации зависимость свойства "получать сведения с ретраями и выбором сервера"
# от работающего враппера жёсткая, тк если он не функционирует должным образом,
# это свойство не обеспечивается, даже если клиент инициализирован и его код доступен.
# Но такая жесткая структура зависимостей справедлива только в рантайме -
# на уровне кода переход из одного варианта в другой заключается по сути
# в переключении ссылок для передачи запросов с обертки клиента на сам клиент.
#
# Успех обращения также зависит от того, выбран ли в пределах разрешённых попыток доступный сервер,
# способный обслужить запрос. При закреплённом эндпоинте требуется доступность именно этого адреса.
#
# Нефункциональные требования: допустимое время одной попытки и всего обращения, включая повторы
# и паузы между ними, допустимая нагрузка на сеть и сервис образов при заданном числе одновременных запросов,
# расход памяти и число открытых соединений на стороне Nova.

# 3. Допустимые изменения.
# Опираемся на пред- и постусловия запроса, функциональные/нефункциональные требования
# и совместимость клиента, враппера и сервера образов.
# Суперспецификация:
# Допустимы любые изменения в реализации этих компонентов, которые:
# сохраняют возможность инициализации клиента и выполнения запроса через управляющий слой,
# сохраняют совместимость поддерживаемых версий API (и формат и смысл запросов и ответов),
# не усиливают предусловия запроса, в частности не требуют доступности всех серверов одновременно,
# не ослабляют постусловия,
# позволяют системе сохранит свойство
# "иметь возможность получать сведения об образах" с оговоренным уровнем стабильности (в конкретном случае
# этот уровень стабильности достигается ретраями и репликами сервера, но фактически сам механизм
# строго не задается, только описывается поведение),
# обеспечивают работу в рамках выбранных нефункциональных требований


# Г. Фильтрация хостов по данным о свободной физической памяти.
#
# Здесь случай более специфичный и конкретный.
# Зависимость: PhysicalRamFilter -> сведения о памяти в объекте HostState.
# Фильтр использует переданное в объекте значение вместо самостоятельного вычисления.
# То есть фильтр зависит как от самих данных, так и от кода, который эти данные поставляет.

# 1. Семантика
# Зависимость сборки - в рассматриваемой связи между поставщиком данных и фильтром отсутствует.
# Типы передаваемых данных во время сборки не проверяются, а код фильтра не импортирует и не вызывает
# код, который проставляет значение - взаимодействие происходит через данные в готовом объекте.
# Зависимость времени выполнения - есть зависимость от типов данных, тк фильтр должен иметь возможность
# вычесть запрошенную память из переданного значения и сравнить результат с порогом.
# При этом проект на Питоне 2.7, и типы там толком не проверяются, но такая ситуация по сути стандарт.
# Функциональные требования
# - определить, проходит ли хост проверку по бюджету физической памяти для указанного запроса ВМ.
# Порог выбирается из метаданных агрегатов (минимум при нескольких допустимых значениях)
# либо из общей константы при отсутствии или некорректности метаданных.
# предусловия:
# переданы HostState проверяемого хоста и объект запроса ВМ с необходимыми полями и методами,
# free_phys_ram_mb содержит конечное числовое значение либо None, memory_mb - конечное
# неотрицательное число в согласованных единицах измерения
# общая настройка limit_ram_mb включает допустимый порог

# постусловия:
# - успешное завершение -
# возвращено булево значение (логику возвращения значения опустил, она достаточно комплексная)
# бюджет памяти не уменьшен, ресурсы интактны, ВМ интактна
# - неуспешное завершение -
# выброшено исключение

# 2. Характеристики
# От реализации фильтра зависит свойство планировщика "отсеивать хосты, на которых
# после размещения ВМ физической памяти останется меньше заданного запаса".
# От источника данных и подготовки HostState зависит соответствие этого решения хосту.
#
# Кроме того, True при None или resize_source_host означает пропуск проверки по этому условию,
# поэтому не является подтверждением наличия требуемого запаса памяти.
# Нефункциональные требования: допустимое время проверки одного хоста и всего набора кандидатов,
# расход CPU и памяти планировщика, допустимый возраст измерений и задержка обновления состояния.

# 3. Допустимые изменения.
# Опираемся на пред- и постусловия проверки, смысл передаваемых данных
# и функциональные/нефункциональные требования к выбору хоста.
# Суперспецификация:
# Допустимы любые изменения фильтра и подготовки данных, которые:
# сохраняют совместимость вызова host_passes и возвращаемого логического результата,
# сохраняют смысл бюджета физической памяти и согласованность единиц измерения,
# не усиливают предусловия,
# не ослабляют постусловия,
# сохраняют правило сравнения с порогом и учёт уже запланированных в рамках запроса размещений,
# позволяют планировщику сохранять свойство "отсеивать хосты с недостаточным запасом памяти
# по предоставленным данным" с оговорёнными исключениями,
# обеспечивают работу в рамках выбранных ограничений времени и ресурсов, в т.ч. актуальность данных



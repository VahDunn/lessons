# также реально существуют (это, разумеется, абстракция для дисков, томов, сети и т.д) и
# доступны на целевом хосте, нет конфликтующих параллельных операций.
# постусловия: успешное завершение - ВМ в состоянии "включена", неуспешное завершение - выброшено исключение
# То есть код действительно выполняется и работает так, как от него ожидает вызывающий


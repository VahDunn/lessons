# А. Включение ВМ через выбранный драйвер гипервизора.
#
# Зависимость: ComputeManager -> конкретный драйвер гипервизора.
# Менеджер делегирует включение ВМ драйверу через power_on(). Для успешного
# запуска драйвер должен действительно выполнить эту операцию.
# Менеджер получает драйвер через load_compute_driver, вроде бы это полиморфизм подтипов.

# 1. Семантика
# Зависимость сборки - тип должен совпадать, проверка типа происходит динамически один раз (без драйвера будет ошибка
# на запуске)
# Зависимость времени выполнения - код действительно выполняется и "как-то" работает
# Функциональные требования
# - включение через метод power_on -
# предусловия - ВМ, которую представляет передаваемый в драйвер объект,
# существует в поле зрения текущего узла, все поля этого объекта принадлежат единой ВМ (связаны общим идентификатором),
# также реально существуют (это, разумеется, абстракция для дисков, томов, сети и т.д) и
# доступны на целевом хосте, нет конфликтующих параллельных операций.
# постусловия - успешное завершение - ВМ в состоянии "включена", неуспешное завершение - выброшено исключение
# То есть код действительно выполняется и работает так, как от него ожидает вызывающий

# 2. Характеристики - поведение Manager примерно на 70% опирается на предоставляемый драйвером функционал.
# Если говорить грубо (перейти от количества к качеству с некоторой абстракцией), от предоставляемого драйвером
# функционала зависит свойство Менеджера "управлять виртуальными машинами". В конкретном случае "обладать
# возможностью включать виртуальные машины" (снова модальности :)
# Можно уточнить нефункциональные требования здесь же, прибавив примерные рамки допустимых
# временных и ресурсных затрат.


class BloomFilter:
    """
    АТД фильтра Блюма для строк.

    Публичный интерфейс АТД:
    - BloomFilter(filter_len=32), создать фильтр заданной длины в битах
    - add(value), добавить строку
    - clear(), очистить фильтр
    - is_value(value), проверить возможное присутствие строки

    Инварианты и гарантии:
    - длина фильтра положительна и не меняется после создания
    - добавленная строка всегда проходит проверку до следующего clear()
    - False означает, что строку не добавляли после создания или очистки
    - True означает возможное присутствие, допускаются ложные срабатывания
    - повторное добавление той же строки не изменяет состояние
    - добавление не отменяет прежние положительные результаты проверок
    """

    def __init__(self, filter_len: int = 32) -> None:
        # предусловие:
        # длина фильтра — положительное целое число
        #
        # постусловие:
        # создан новый пустой фильтр заданной длины, по умолчанию 32 бита
        # is_value() возвращает False для любой строки
        #
        # если предусловие нарушено:
        # вызывается ValueError, объект не создаётся

        if (
            not isinstance(filter_len, int)
            or isinstance(filter_len, bool)
            or filter_len <= 0
        ):
            raise ValueError("filter_len must be a positive integer")

        self._filter_len = filter_len
        self._bits = 0

        return None

    # команды

    def add(self, value: str) -> None:
        # предусловие:
        # значение имеет тип str
        #
        # постусловие:
        # is_value() для добавленной строки возвращает True
        # прежние положительные результаты проверок сохраняются
        # повторное добавление той же строки не изменяет состояние
        #
        # если предусловие нарушено:
        # вызывается TypeError, фильтр не изменяется

        self._bits |= self._value_mask(value)

        return None

    def clear(self) -> None:
        # предусловие:
        # отсутствует
        #
        # постусловие:
        # фильтр возвращён в начальное пустое состояние
        # is_value() возвращает False для любой строки
        # длина фильтра не изменилась

        self._bits = 0

        return None

    # запросы

    def is_value(self, value: str) -> bool:
        # предусловие:
        # значение имеет тип str
        #
        # результат:
        # False — строку точно не добавляли после создания или очистки
        # True — строка могла быть добавлена, ответ может быть ложноположительным
        # для добавленной после создания или очистки строки всегда возвращается True
        # состояние фильтра не изменяется
        #
        # если предусловие нарушено:
        # вызывается TypeError, фильтр не изменяется

        mask = self._value_mask(value)
        result = (self._bits & mask) == mask

        return result

    # закрытая операция реализации

    def _value_mask(self, value: str) -> int:
        # Вычисляет два полиномиальных хеша с множителями 17 и 223, начиная с 0.
        # Маска объединяет биты обеих позиций. Если позиции совпали, в маске
        # будет один бит. Для пустой строки оба хеша равны нулю.

        if not isinstance(value, str):
            raise TypeError("value must be a string")

        first_hash = 0
        second_hash = 0

        for symbol in value:
            code = ord(symbol)
            first_hash = (first_hash * 17 + code) % self._filter_len
            second_hash = (second_hash * 223 + code) % self._filter_len

        result = (1 << first_hash) | (1 << second_hash)

        return result
